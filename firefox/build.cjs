// Keep Safari's install file untouched. Fail if a source hook changes, rather
// than silently producing an incomplete Firefox adaptation.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');

const target = path.join(__dirname, 'Quiet-Leaf-Firefox.user.js');
function build() {
  let source = fs.readFileSync(path.join(__dirname, '../Quiet-Leaf.user.js'), 'utf8');
  const adapter = fs.readFileSync(path.join(__dirname, 'adapter.js'), 'utf8');
  const replace = (before, after) => {
    assert.equal(source.split(before).length, 2, 'Expected one Firefox build hook: ' + before);
    source = source.replace(before, () => after);
  };
  replace('// @name         Quiet Leaf — Internet Archive', '// @name         Quiet Leaf — Internet Archive (Firefox)');
  // Firefox ships the same version as the Safari reader. This hook still fails
  // the build when that version string moves.
  replace('// @version      0.6.5', '// @version      0.6.5');
  replace('// ==/UserScript==', '// @supportURL   https://github.com/Jack-Reason/quiet-leaf/issues/2\n// ==/UserScript==\n\n// Generated by firefox/build.cjs from Quiet-Leaf.user.js and firefox/adapter.js.');
  replace("  'use strict';", "  'use strict';\n" + adapter.split('\n').map(line => line ? '  ' + line : '').join('\n'));
  replace("new CustomEvent('bookmarkSelected',{detail:{bookmark:{id:index,leafNum:index}}})", 'firefoxBookmarkEvent(index)');
  replace('e.detail?.props?.index ?? e.detail?.props?.firstIndex', 'firefoxPageIndex(e)');
  replace('Read quietly · 0.6.5', 'Read quietly · Firefox 0.6.5');
  replace('Saved on this iPad', 'Saved on this device');
  replace('Fullscreen is unavailable in this Safari window.', 'Fullscreen is unavailable in this Firefox window.');
  replace('Safari declined fullscreen. Two-finger tap and try Full screen.', 'Firefox declined fullscreen. Tap ⋯ and try Full screen.');
  return source;
}

if (require.main === module) {
  const source = build();
  if (process.argv.includes('--check')) {
    assert.equal(fs.readFileSync(target, 'utf8'), source, 'Run npm run build:firefox to refresh the Firefox userscript');
    console.log('PASS Firefox userscript matches the Safari source and Firefox adapter');
  } else {
    fs.writeFileSync(target, source);
    console.log('Built firefox/Quiet-Leaf-Firefox.user.js');
  }
}
module.exports = {build};
